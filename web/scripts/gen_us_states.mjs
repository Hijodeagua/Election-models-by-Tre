// Regenerates app/lib/us-states-paths.ts from the us-atlas package.
//
//   cd web
//   npm install --no-save us-atlas@3 topojson-client@3 d3-geo@3
//   node scripts/gen_us_states.mjs
//
// us-atlas ships U.S. Census cartographic boundaries pre-projected with
// d3.geoAlbersUsa into a 975×610 frame (Alaska and Hawaii inset), so the
// output needs no projection at render time — just <path d>.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import * as topojson from 'topojson-client';
import { geoPath } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = require('us-atlas/states-albers-10m.json');

const FIPS_TO_ABBR = {
  '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT',
  '10': 'DE', '11': 'DC', '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL',
  '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY', '22': 'LA', '23': 'ME', '24': 'MD',
  '25': 'MA', '26': 'MI', '27': 'MN', '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE',
  '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM', '36': 'NY', '37': 'NC', '38': 'ND',
  '39': 'OH', '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI', '45': 'SC', '46': 'SD',
  '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA', '54': 'WV',
  '55': 'WI', '56': 'WY',
};

const features = topojson.feature(topo, topo.objects.states).features;
const pathGen = geoPath(null).digits(1);

const states = {};
for (const f of features) {
  const abbr = FIPS_TO_ABBR[f.id];
  if (!abbr) continue;
  const [cx, cy] = pathGen.centroid(f);
  states[abbr] = {
    name: f.properties.name,
    d: pathGen(f),
    cx: Number(cx.toFixed(1)),
    cy: Number(cy.toFixed(1)),
  };
}
const borders = pathGen(topojson.mesh(topo, topo.objects.states, (a, b) => a !== b));

const out = `// GENERATED by scripts/gen_us_states.mjs from us-atlas@3 states-albers-10m.json
// (U.S. Census cartographic boundaries, pre-projected Albers USA, 975×610 viewBox).
// Do not hand-edit; re-run the generator instead.

export const US_MAP_VIEWBOX = '0 0 975 610';

export interface StateShape {
  name: string;
  d: string;
  cx: number;
  cy: number;
}

export const US_STATES: Record<string, StateShape> = ${JSON.stringify(states)};

// Interior borders only (shared edges), for a single crisp stroke layer.
export const US_STATE_BORDERS = ${JSON.stringify(borders)};
`;

const dest = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'app', 'lib', 'us-states-paths.ts');
fs.writeFileSync(dest, out);
console.log(`wrote ${dest} (${Object.keys(states).length} states, ${out.length} bytes)`);
